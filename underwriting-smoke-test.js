'use strict';
const assert=require('assert');
const {rateStock}=require('./engine/rating-engine');
const stock={price:{current:100},sector:'Technology'};
const forecast={forecastReliabilityScore:75};
const quality={qualityScore:90,confidenceScore:90};
const v={expectedCAGR:.23,underwrittenCAGR:.14,marginOfSafety:.40,requiredReturnBuyPrice:120,hurdleReturnPrice:150,methodAgreementScore:85,valuationConfidenceScore:85,methods:[{},{},{}],independentMethodCount:3,modelSupport:'standard',underwriting:{flags:['large_unproven_fcf_margin_expansion']}};
assert.strictEqual(rateStock(stock,forecast,quality,v).rating,'Watch','stressed return below 15% cannot be Buy');
assert.strictEqual(rateStock(stock,forecast,quality,{...v,underwrittenCAGR:.20}).rating,'Exceptional Buy');
const {forecastUnderwriting}=require('./engine/valuation-engine');
const years=[2021,2022,2023,2024,2025].map((year,i)=>({year,revenue:100*(1.08**i),fcf:100*(1.08**i)*.06,netIncome:100*(1.08**i)*.05}));
const projected={rows:Array.from({length:10},(_,i)=>({revenue:years.at(-1).revenue*(1.12**(i+1)),fcfMargin:.20,netMargin:.16})),forecastReliabilityScore:65};
const stressed=forecastUnderwriting({financials:{years}},projected,{});
assert(Math.abs(stressed.historicalFCFMargin-.06)<1e-9,'derive FCF margin from reported FCF/revenue');
assert(stressed.annualStress>=.03,'large unproven dual margin expansion must meaningfully reduce entry price');
assert(stressed.flags.includes('large_unproven_fcf_margin_expansion'));
assert(stressed.flags.includes('large_unproven_net_margin_expansion'));
const unavailable=forecastUnderwriting({financials:{years:years.map(({fcf,...rest})=>rest)}},projected,{});
assert(unavailable.flags.includes('fcf_margin_history_unavailable'),'missing FCF history must not silently pass');
assert(unavailable.annualStress>0);
console.log('Underwriting rating and historical-margin regression tests passed');
